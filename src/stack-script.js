// Generate a setup script for a set of MCP servers: one file the user runs with
// Node (or tsx) that checks prerequisites, asks for each required setting
// (secrets hidden, never written into the script), backs up and updates the
// Claude Desktop, Cursor and VS Code configs, and registers the servers with
// Claude Code. --dry-run shows what it would change.

/** servers: [{ key, title, id, kind: 'local'|'remote'|'none', command, args, url, transport, settings: [{ name, secret, description, header, value }], note }] */
export function setupScript(servers, { format = 'mjs', generatedAt = new Date().toISOString() } = {}) {
  const data = JSON.stringify(servers, null, 2);
  const ts = format === 'ts';
  const runWith = ts ? 'npx tsx setup-mcp.ts' : 'node setup-mcp.mjs';
  const names = servers.map((s) => s.title || s.key).join(', ');
  return `#!/usr/bin/env node
${ts ? '// @ts-nocheck\n' : ''}// Set up ${servers.length} MCP server${servers.length === 1 ? '' : 's'} in Claude Desktop, Claude Code, Cursor and VS Code:
//   ${names.slice(0, 300)}
// Generated by MCP Browser on ${generatedAt.slice(0, 10)}. Read it before running it.
//
//   ${runWith}                    set up every client found on this computer
//   ${runWith} --dry-run          show what would change, change nothing
//   ${runWith} --clients=desktop,code,cursor,vscode
//
// It asks for each required setting (keys are typed hidden and never saved in
// this file; a setting already in your environment is used as is), backs up
// every config file it changes (*.backup-<time>), and only adds or replaces the
// servers listed below. Claude Desktop and Cursor keep keys in their config file
// in plain text; VS Code gets \${input:...} prompts instead, so keys stay out of
// its file. Needs Node 18+.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import readline from 'node:readline';
import { spawnSync } from 'node:child_process';

const SERVERS = ${data};

const argv = process.argv.slice(2);
const DRY = argv.includes('--dry-run');
const only = (argv.find((a) => a.startsWith('--clients=')) || '').split('=')[1];
// MCP Browser runs this itself ("Set up now"): values arrive in MCPB_VALUES, nothing is asked.
const REMOVE = argv.includes('--remove'); // take these servers out of the configs instead
const INTERACTIVE = !argv.includes('--non-interactive') && Boolean(process.stdin.isTTY);
let GIVEN = {};
try {
  GIVEN = JSON.parse(process.env.MCPB_VALUES || '{}') || {};
} catch {}
const SECRETS = new Set(); // secret values, hidden in everything this prints
const hide = (t) => {
  t = String(t);
  for (const v of SECRETS) if (v.length >= 4) t = t.split(v).join('***');
  return t;
};
const home = os.homedir();
const win = process.platform === 'win32';
const support = process.platform === 'darwin' ? path.join(home, 'Library', 'Application Support') : win ? process.env.APPDATA || path.join(home, 'AppData', 'Roaming') : path.join(home, '.config');

const which = (cmd) => spawnSync(win ? 'where' : 'which', [cmd], { stdio: 'ignore' }).status === 0;
const stamp = new Date().toISOString().replace(/[-:]/g, '').replace(/\\..*/, '').replace('T', '-');
const say = (...a) => console.log(...a);

// ---------- which clients ----------
const CLIENTS = {
  desktop: { label: 'Claude Desktop', file: path.join(support, 'Claude', 'claude_desktop_config.json'), present: () => fs.existsSync(path.join(support, 'Claude')) },
  cursor: { label: 'Cursor', file: path.join(home, '.cursor', 'mcp.json'), present: () => fs.existsSync(path.join(home, '.cursor')) },
  vscode: { label: 'VS Code', file: path.join(support, 'Code', 'User', 'mcp.json'), present: () => fs.existsSync(path.join(support, 'Code', 'User')) },
  code: { label: 'Claude Code', present: () => which('claude') },
};
if (argv.includes('--list-clients')) {
  console.log(JSON.stringify(Object.entries(CLIENTS).map(([id, c]) => ({ id, label: c.label, present: c.present(), file: c.file || null }))));
  process.exit(0);
}
const chosen = only ? only.split(',').map((x) => x.trim()).filter((x) => CLIENTS[x]) : Object.keys(CLIENTS).filter((k) => CLIENTS[k].present());
if (!chosen.length) {
  say('No MCP clients found (Claude Desktop, Claude Code, Cursor, VS Code). Use --clients=... to choose.');
  process.exit(1);
}
say(\`\${REMOVE ? 'Removing' : 'Setting up'} \${SERVERS.length} server(s) for: \${chosen.map((k) => CLIENTS[k].label).join(', ')}\${DRY ? '  (dry run: nothing will change)' : ''}\\n\`);

// ---------- prerequisites ----------
const needs = new Set(REMOVE ? [] : SERVERS.filter((s) => s.kind === 'local').map((s) => s.command));
if (!REMOVE && SERVERS.some((s) => s.kind === 'remote') && chosen.includes('desktop')) needs.add('npx');
const HOW = { uvx: 'install uv: brew install uv   (or: curl -LsSf https://astral.sh/uv/install.sh | sh)', docker: 'install Docker Desktop: https://www.docker.com/products/docker-desktop/', npx: 'install Node.js: https://nodejs.org', dnx: 'install the .NET 10 SDK: https://dotnet.microsoft.com/download' };
let missing = 0;
for (const cmd of needs) {
  if (which(cmd)) continue;
  missing++;
  say(\`! \${cmd} is not installed: \${HOW[cmd] || 'install it first'}\`);
}
if (missing) say('  The servers that need it are set up anyway; they start working once it is installed.\\n');

// ---------- settings ----------
function ask(question, hidden) {
  return new Promise((resolve) => {
    const rl = readline.createInterface({ input: process.stdin, output: process.stdout, terminal: true });
    if (hidden) {
      rl._writeToOutput = (s) => rl.output.write(s.startsWith(question) ? s : s.replace(/[^\\r\\n]/g, '*'));
    }
    rl.question(question, (a) => {
      rl.close();
      if (hidden) process.stdout.write('\\n');
      resolve(a.trim());
    });
  });
}
const values = {}; // server key → { NAME: value }
const skipped = [];
for (const s of REMOVE ? [] : SERVERS) {
  if (s.kind === 'none') continue;
  values[s.key] = {};
  for (const st of s.settings) {
    const given = GIVEN[s.key]?.[st.name];
    let v = given || process.env[st.name] || st.value || '';
    if (!given && process.env[st.name]) say(\`  \${s.title}: using \${st.name} from your environment\`);
    else if (!v && !DRY && INTERACTIVE) {
      say(\`\\n\${s.title} needs \${st.name}\${st.secret ? ' (secret)' : ''}\${st.description ? ': ' + st.description : ''}\`);
      v = await ask(\`  \${st.name} (leave empty to skip this server): \`, st.secret);
    } else if (!v && DRY && !argv.includes('--non-interactive')) v = \`<\${st.name}>\`; // a CLI dry run shows where it goes
    if (!v) {
      skipped.push(s.title);
      delete values[s.key];
      break;
    }
    if (st.secret && !/^<.*>$/.test(v)) SECRETS.add(v);
    values[s.key][st.name] = v;
  }
}
const ready = SERVERS.filter((s) => values[s.key]);

// ---------- config files ----------
function readJson(file) {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch (e) {
    if (e.code === 'ENOENT') return {};
    throw new Error(\`\${file} is not valid JSON (\${e.message}); fix or move it, then run this again.\`);
  }
}
const tilde = (f) => (f.startsWith(home) ? '~' + f.slice(home.length) : f);
function writeJson(file, obj, label, changed = [], prop = 'mcpServers') {
  const others = Object.keys(obj[prop] || {}).filter((k) => !changed.includes(k)).length;
  if (DRY) {
    if (!changed.length) return say(\`\\n\${label} (\${tilde(file)}): no change\`);
    say(\`\\n\${label} (\${tilde(file)}): would \${REMOVE ? 'remove' : 'add or update'} \${changed.join(', ')}\${others ? \`; the \${others} other server\${others === 1 ? '' : 's'} in it stay as they are\` : ''}\`);
    if (!REMOVE) say(hide(JSON.stringify(Object.fromEntries(changed.map((k) => [k, obj[prop][k]])), null, 2)));
    return;
  }
  if (!changed.length) return;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (fs.existsSync(file)) fs.copyFileSync(file, \`\${file}.backup-\${stamp}\`);
  fs.writeFileSync(file, JSON.stringify(obj, null, 2) + '\\n', { mode: 0o600 });
  say(\`✓ \${label}: updated \${tilde(file)}\${fs.existsSync(\`\${file}.backup-\${stamp}\`) ? ' (backup saved next to it)' : ''}\`);
}
const envOf = (s) => Object.fromEntries(s.settings.filter((x) => !x.header).map((x) => [x.name, values[s.key][x.name]]));
const headersOf = (s, f = (x) => values[s.key][x.name]) => Object.fromEntries(s.settings.filter((x) => x.header).map((x) => [x.name, f(x)]));
const has = (o) => Object.keys(o).length > 0;

if (REMOVE) {
  const keys = SERVERS.map((s) => s.key);
  for (const [id, prop] of [['desktop', 'mcpServers'], ['cursor', 'mcpServers'], ['vscode', 'servers']]) {
    if (!chosen.includes(id) || !fs.existsSync(CLIENTS[id].file)) continue;
    const c = readJson(CLIENTS[id].file);
    const gone = keys.filter((k) => c[prop] && k in c[prop]);
    if (!gone.length) {
      say(\`  \${CLIENTS[id].label}: none of these servers are in it\`);
      continue;
    }
    for (const k of gone) delete c[prop][k];
    if (id === 'vscode' && Array.isArray(c.inputs)) c.inputs = c.inputs.filter((i) => !gone.some((k) => String(i.id).startsWith(k.replace(/[^A-Za-z0-9_-]/g, '-') + '-')));
    writeJson(CLIENTS[id].file, c, CLIENTS[id].label, gone, prop);
  }
  if (chosen.includes('code')) {
    for (const k of keys) {
      if (DRY) {
        say(\`Claude Code: would run  claude mcp remove -s user \${k}\`);
        continue;
      }
      const r = spawnSync('claude', ['mcp', 'remove', '-s', 'user', k], { stdio: ['ignore', 'pipe', 'pipe'], encoding: 'utf8' });
      say(r.status === 0 ? \`✓ Claude Code: removed \${k}\` : \`  Claude Code: \${k} was not there\`);
    }
  }
  if (!DRY) say(\`\nRestart \${chosen.filter((k) => k !== 'code').map((k) => CLIENTS[k].label).join(', ') || 'your MCP clients'} to drop them.\`);
  process.exit(0);
}
// Same server already there under another name (same package or URL)? Leave it alone.
const sig = (e) => (e && (e.url || [e.command, ...(e.args || [])].filter((x) => !/^(-y|--yes)$/.test(x)).join(' '))) || '';
function addAll(c, prop, label, entryOf) {
  c[prop] ||= {};
  const changed = [];
  for (const s of ready) {
    const e = entryOf(s);
    const same = Object.keys(c[prop]).find((k) => k !== s.key && sig(c[prop][k]) && sig(c[prop][k]) === sig(e));
    if (same) {
      say(\`  \${label}: already has \${s.title} as "\${same}", left as is\`);
      continue;
    }
    c[prop][s.key] = e;
    changed.push(s.key);
  }
  return changed;
}
if (chosen.includes('desktop')) {
  const c = readJson(CLIENTS.desktop.file);
  const changed = addAll(c, 'mcpServers', 'Claude Desktop', (s) => {
    if (s.kind === 'local') return { command: s.command, args: s.args, ...(has(envOf(s)) ? { env: envOf(s) } : {}) };
    // Claude Desktop reaches hosted servers through the mcp-remote bridge.
    const hdr = s.settings.filter((x) => x.header);
    const envName = (x) => 'MCP_' + x.name.replace(/[^A-Za-z0-9]/g, '_').toUpperCase();
    return { command: 'npx', args: ['-y', 'mcp-remote', s.url, ...hdr.flatMap((x) => ['--header', \`\${x.name}:\\\${\${envName(x)}}\`])], ...(hdr.length ? { env: Object.fromEntries(hdr.map((x) => [envName(x), values[s.key][x.name]])) } : {}) };
  });
  writeJson(CLIENTS.desktop.file, c, 'Claude Desktop', changed, 'mcpServers');
}
if (chosen.includes('cursor')) {
  const c = readJson(CLIENTS.cursor.file);
  const changed = addAll(c, 'mcpServers', 'Cursor', (s) => (s.kind === 'local' ? { command: s.command, args: s.args, ...(has(envOf(s)) ? { env: envOf(s) } : {}) } : { url: s.url, ...(has(headersOf(s)) ? { headers: headersOf(s) } : {}) }));
  writeJson(CLIENTS.cursor.file, c, 'Cursor', changed, 'mcpServers');
}
if (chosen.includes('vscode')) {
  // VS Code asks for secrets itself (\${input:...}), so they never sit in this file.
  const c = readJson(CLIENTS.vscode.file);
  c.inputs ||= [];
  const input = (s, x) => {
    const id = \`\${s.key}-\${x.name}\`.replace(/[^A-Za-z0-9_-]/g, '-');
    if (!c.inputs.some((i) => i.id === id)) c.inputs.push({ type: 'promptString', id, description: \`\${s.title}: \${x.name}\`, password: true });
    return \`\\\${input:\${id}}\`;
  };
  const changed = addAll(c, 'servers', 'VS Code', (s) => {
    const val = (x) => (x.secret ? input(s, x) : values[s.key][x.name]);
    if (s.kind === 'local') {
      const env = Object.fromEntries(s.settings.filter((x) => !x.header).map((x) => [x.name, val(x)]));
      return { type: 'stdio', command: s.command, args: s.args, ...(has(env) ? { env } : {}) };
    }
    const headers = headersOf(s, val);
    return { type: s.transport === 'sse' ? 'sse' : 'http', url: s.url, ...(has(headers) ? { headers } : {}) };
  });
  writeJson(CLIENTS.vscode.file, c, 'VS Code', changed, 'servers');
}
if (chosen.includes('code')) {
  for (const s of ready) {
    const args =
      s.kind === 'local'
        ? ['mcp', 'add', '-s', 'user', ...Object.entries(envOf(s)).flatMap(([k, v]) => ['-e', \`\${k}=\${v}\`]), s.key, '--', s.command, ...s.args]
        : ['mcp', 'add', '-s', 'user', '--transport', s.transport === 'sse' ? 'sse' : 'http', s.key, s.url, ...Object.entries(headersOf(s)).flatMap(([k, v]) => ['--header', \`\${k}: \${v}\`])];
    if (DRY) {
      say(\`\\nClaude Code: would run  claude \${hide(args.map((a) => (/[\\s'"]/.test(a) ? JSON.stringify(a) : a)).join(' '))}\`);
      continue;
    }
    spawnSync('claude', ['mcp', 'remove', '-s', 'user', s.key], { stdio: 'ignore' }); // replace an older entry
    const r = spawnSync('claude', args, { stdio: ['ignore', 'pipe', 'pipe'], encoding: 'utf8' });
    say(r.status === 0 ? \`✓ Claude Code: added \${s.key}\` : \`! Claude Code: could not add \${s.key}: \${hide((r.stderr || r.stdout || r.error?.message || '').trim().split('\\n')[0])}\`);
  }
}

// ---------- summary ----------
const manual = SERVERS.filter((s) => s.kind === 'none');
say('');
if (ready.length) say(\`\${DRY ? 'Would set up' : 'Done'}: \${ready.map((s) => s.key).join(', ')}.\`);
if (skipped.length) say(\`Skipped, a setting is missing: \${skipped.join(', ')}. Fill it in and run this again to add \${skipped.length === 1 ? 'it' : 'them'}.\`);
for (const s of manual) say(\`Set up by hand: \${s.title}. \${s.note || ''}\`);
if (!DRY && ready.length) say(\`Restart \${chosen.filter((k) => k !== 'code').map((k) => CLIENTS[k].label).join(', ') || 'your MCP clients'} to load the new servers.\`);
`;
}
